"""npm versions and ranges: SemVer 2.0 as node-semver 7 (npm 10) reads them (SPEC-MULTI-ECOSYSTEM.md §5.5, Q8).

The byte key is ported from design/schema-check/sortkey_proto.py (checked against node-semver pairwise). Ranges are
desugared the way node-semver does into sets of primitive comparators; a prerelease version satisfies a set only if
one of its comparators carries a prerelease on the same major.minor.patch (npm without `includePrerelease`).
Compatibility is checked against vectors generated by node-semver itself (scripts/generate_semver_vectors.sh).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from functools import lru_cache

from app.ecosystems.base import Bump, Constraint, InvalidVersion
from app.ecosystems.versions_common import encode_number, fallback_sort_key

MAX_SAFE_INTEGER = 2**53 - 1
_NUM = r"0|[1-9]\d*"
_PRE_ID = r"(?:0|[1-9]\d*|\d*[a-zA-Z-][a-zA-Z0-9-]*)"
_VERSION = re.compile(
    rf"^v?({_NUM})\.({_NUM})\.({_NUM})(?:-({_PRE_ID}(?:\.{_PRE_ID})*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$"
)
Identifier = int | str


@dataclass(frozen=True, slots=True)
class SemVer:
    major: int
    minor: int
    patch: int
    prerelease: tuple[Identifier, ...] = ()

    @property
    def triple(self) -> tuple[int, int, int]:
        return (self.major, self.minor, self.patch)

    def compare(self, other: SemVer) -> int:
        if self.triple != other.triple:
            return -1 if self.triple < other.triple else 1
        return _compare_prerelease(self.prerelease, other.prerelease)


def _compare_prerelease(a: tuple[Identifier, ...], b: tuple[Identifier, ...]) -> int:
    if not a or not b:
        return (len(b) > 0) - (len(a) > 0)   # a release is greater than any of its prereleases
    for x, y in zip(a, b):
        if x == y:
            continue
        if isinstance(x, int) and isinstance(y, int):
            return -1 if x < y else 1
        if isinstance(x, int):
            return -1                      # numeric identifiers sort below alphanumeric ones
        if isinstance(y, int):
            return 1
        return -1 if x < y else 1
    return (len(a) > len(b)) - (len(a) < len(b))


def _number(text: str, raw: str) -> int:
    value = int(text)
    if value > MAX_SAFE_INTEGER:
        raise InvalidVersion(f"{raw}: {text} is above 2**53-1")
    return value


@lru_cache(maxsize=65536)
def parse(raw: str) -> SemVer:
    match = _VERSION.match(raw.strip())
    if match is None:
        raise InvalidVersion(raw)
    prerelease: tuple[Identifier, ...] = ()
    if match[4]:
        # node-semver keeps a numeric identifier above 2**53-1 as a string; such versions are rejected here instead,
        # so the byte key (numeric identifiers by value) never disagrees with it.
        prerelease = tuple(_number(part, raw) if part.isdigit() else part for part in match[4].split("."))
    return SemVer(_number(match[1], raw), _number(match[2], raw), _number(match[3], raw), prerelease)


def _key(version: SemVer) -> bytes:
    out = b"".join(encode_number(str(n)) for n in version.triple)
    if not version.prerelease:
        return out + b"\x02"                       # a release sorts after every prerelease of it
    out += b"\x01"
    for ident in version.prerelease:
        if isinstance(ident, int):
            out += b"\x01" + encode_number(str(ident))
        else:
            out += b"\x02" + ident.encode() + b"\x00"
    return out + b"\x00"                           # fewer identifiers sort first


# --- ranges ----------------------------------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Comparator:
    operator: str                                  # "<", "<=", ">", ">=", "=" or "" (any)
    version: SemVer | None                         # None: matches any version (`*`)

    def test(self, version: SemVer) -> bool:
        if self.version is None:
            return True
        cmp = version.compare(self.version)
        return {"<": cmp < 0, "<=": cmp <= 0, ">": cmp > 0, ">=": cmp >= 0, "=": cmp == 0}[self.operator]


_PARTIAL = re.compile(
    rf"^v?(?P<major>{_NUM}|[xX*])(?:\.(?P<minor>{_NUM}|[xX*])(?:\.(?P<patch>{_NUM}|[xX*])"
    rf"(?:-(?P<pre>{_PRE_ID}(?:\.{_PRE_ID})*))?(?:\+[0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*)?)?)?$"
)
_COMPARATOR = re.compile(r"^(?P<op><=|>=|<|>|=|~>|~|\^)?\s*(?P<version>\S*)$")
_HYPHEN = re.compile(r"^\s*(\S+)\s+-\s+(\S+)\s*$")
_ANY = Comparator("", None)
_NOTHING = Comparator("<", SemVer(0, 0, 0, (0,)))


@dataclass(frozen=True, slots=True)
class _Partial:
    major: int | None
    minor: int | None
    patch: int | None
    prerelease: tuple[Identifier, ...]

    def floor(self) -> SemVer:
        return SemVer(self.major or 0, self.minor or 0, self.patch or 0, self.prerelease)


def _partial(text: str, raw: str) -> _Partial:
    match = _PARTIAL.match(text)
    if match is None:
        raise InvalidVersion(f"invalid npm range {raw!r}")

    def part(name: str) -> int | None:
        value = match[name]
        return None if value is None or value in "xX*" else _number(value, raw)

    major, minor, patch = part("major"), part("minor"), part("patch")
    # A wildcard swallows what follows it: 1.x.3 is 1.x.
    if major is None:
        minor = patch = None
    elif minor is None:
        patch = None
    prerelease: tuple[Identifier, ...] = ()
    if match["pre"] and patch is not None:
        prerelease = tuple(_number(p, raw) if p.isdigit() else p for p in match["pre"].split("."))
    return _Partial(major, minor, patch, prerelease)


def _lower(value: SemVer) -> Comparator:
    return Comparator(">=", value)


def _upper_before(major: int, minor: int, patch: int) -> Comparator:
    return Comparator("<", SemVer(major, minor, patch, (0,)))


def _tilde(p: _Partial) -> list[Comparator]:
    if p.major is None:
        return [_ANY]
    if p.minor is None:
        return [_lower(p.floor()), _upper_before(p.major + 1, 0, 0)]
    return [_lower(p.floor()), _upper_before(p.major, p.minor + 1, 0)]


def _caret(p: _Partial) -> list[Comparator]:
    if p.major is None:
        return [_ANY]
    if p.minor is None:
        return [_lower(p.floor()), _upper_before(p.major + 1, 0, 0)]
    if p.patch is None:
        if p.major == 0:
            return [_lower(p.floor()), _upper_before(0, p.minor + 1, 0)]
        return [_lower(p.floor()), _upper_before(p.major + 1, 0, 0)]
    if p.major == 0:
        if p.minor == 0:
            return [_lower(p.floor()), _upper_before(0, 0, p.patch + 1)]
        return [_lower(p.floor()), _upper_before(0, p.minor + 1, 0)]
    return [_lower(p.floor()), _upper_before(p.major + 1, 0, 0)]


def _x_range(operator: str, p: _Partial) -> list[Comparator]:
    """`1.2`, `>=1.2`, `<1.x`, `=1`: a partial version with a primitive operator."""
    if p.major is None:
        return [_NOTHING] if operator in ("<", ">") else [_ANY]
    if p.patch is not None:
        return [Comparator(operator or "=", p.floor())]
    if operator in ("", "="):
        return _tilde(p) if p.minor is not None else [_lower(p.floor()), _upper_before(p.major + 1, 0, 0)]
    if operator == ">":                            # >1 is >=2.0.0, >1.2 is >=1.3.0
        if p.minor is None:
            return [_lower(SemVer(p.major + 1, 0, 0))]
        return [_lower(SemVer(p.major, p.minor + 1, 0))]
    if operator == "<=":                           # <=1 is <2.0.0-0, <=1.2 is <1.3.0-0
        if p.minor is None:
            return [_upper_before(p.major + 1, 0, 0)]
        return [_upper_before(p.major, p.minor + 1, 0)]
    if operator == "<":                            # <1.2 is <1.2.0-0
        return [_upper_before(p.major, p.minor or 0, 0)]
    return [_lower(p.floor())]                     # >=1.2 is >=1.2.0


def _hyphen(low_text: str, high_text: str, raw: str) -> list[Comparator]:
    low, high = _partial(low_text, raw), _partial(high_text, raw)
    out = [] if low.major is None else [_lower(low.floor())]
    if high.major is None:
        return out or [_ANY]
    if high.minor is None:
        return [*out, _upper_before(high.major + 1, 0, 0)]
    if high.patch is None:
        return [*out, _upper_before(high.major, high.minor + 1, 0)]
    return [*out, Comparator("<=", high.floor())]


def _comparator_set(text: str, raw: str) -> list[Comparator]:
    hyphen = _HYPHEN.match(text)
    if hyphen:
        return _hyphen(hyphen[1], hyphen[2], raw)
    # Operators may be separated from their version by spaces (`>= 1.2.3`): glue them first.
    tokens = re.sub(r"(<=|>=|<|>|=|~>|~|\^)\s+", r"\1", text.strip()).split()
    comparators: list[Comparator] = []
    for token in tokens or ["*"]:
        match = _COMPARATOR.match(token)
        if match is None:
            raise InvalidVersion(f"invalid npm range {raw!r}")
        operator, partial = match["op"] or "", _partial(match["version"] or "*", raw)
        if operator in ("~", "~>"):
            comparators += _tilde(partial)
        elif operator == "^":
            comparators += _caret(partial)
        else:
            comparators += _x_range(operator, partial)
    return comparators


@lru_cache(maxsize=16384)
def parse_range(raw: str) -> tuple[tuple[Comparator, ...], ...]:
    return tuple(tuple(_comparator_set(part, raw)) for part in raw.split("||"))


def _satisfies_set(version: SemVer, comparators: tuple[Comparator, ...]) -> bool:
    if not all(c.test(version) for c in comparators):
        return False
    if not version.prerelease:
        return True
    # npm (no includePrerelease): a prerelease only matches next to a comparator that names one on its triple.
    return any(c.version is not None and c.version.prerelease and c.version.triple == version.triple
               for c in comparators)


@dataclass(frozen=True, slots=True)
class NpmConstraint:
    _raw: str
    _sets: tuple[tuple[Comparator, ...], ...]

    def contains(self, version: str) -> bool:
        try:
            parsed = parse(version)
        except InvalidVersion:
            return False
        return any(_satisfies_set(parsed, comparators) for comparators in self._sets)

    def raw(self) -> str:
        return self._raw


class NpmVersionScheme:
    def validate(self, raw: str) -> None:
        parse(raw)

    def sort_key(self, raw: str) -> bytes:
        try:
            return _key(parse(raw))
        except InvalidVersion:
            return fallback_sort_key(raw)

    def is_prerelease(self, raw: str) -> bool:
        try:
            return bool(parse(raw).prerelease)
        except InvalidVersion:
            return False

    def bump(self, previous: str | None, current: str) -> Bump | None:
        if previous is None:
            return None
        try:
            prev, cur = parse(previous), parse(current)
        except InvalidVersion:
            return "other"
        if cur.prerelease:
            return "pre"
        if cur.compare(prev) <= 0:
            return "other"
        if cur.major != prev.major:
            return "major"
        if cur.minor != prev.minor:
            return "minor"
        return "patch"

    def constraint(self, raw: str) -> Constraint:
        """A node-semver range; dist-tags (`latest`) and URLs are not ranges and raise InvalidVersion."""
        return NpmConstraint(raw, parse_range(raw.strip()))
