# Numbers a floating bound pins, by behavior; the rest (and any prerelease) floats.
_PINNED = {"Major": 0, "Minor": 1, "Patch": 2, "Revision": 3, "Prerelease": 4, "PrereleaseMajor": 0,
           "PrereleaseMinor": 1, "PrereleasePatch": 2, "PrereleaseRevision": 3}
_STAR_LEVEL = ("Major", "Minor", "Patch", "Revision")


@dataclass(frozen=True, slots=True)
class Float:
    """The floating lower bound of a range: which numbers are fixed and which prerelease labels it accepts."""

    behavior: str                                  # NuGetVersionFloatBehavior: Major, Minor, ..., AbsoluteLatest
    min: Version
    prefix: str                                    # label prefix of `1.0.0-beta*`, "" for any

    def satisfies(self, version: Version) -> bool:
        if self.behavior == "AbsoluteLatest":
            return True
        pinned = _PINNED[self.behavior]
        if version.numbers[:pinned] != self.min.numbers[:pinned]:
            return False
        if self.behavior in _STAR_LEVEL:
            return not version.is_prerelease       # `1.*` does not float into prereleases
        return not version.is_prerelease or ".".join(version.labels).lower().startswith(self.prefix.lower())


def _parse_float(text: str, raw: str) -> Float | None:
    """`FloatRange.TryParse`: None when `text` is not a floating version (the caller then reads a plain one).

    The star must be the last character of the version part, so `1.0.* ` or `[1.* ,2.0)` are not floating. Its
    position among the dots, not the digits before it, decides what floats: `1.0*` is `1.*`.
    """
    if not text.endswith("*"):
        return None
    core, dash, label = text.partition("-")
    prefix = label[:-1] if dash else ""
    parts = core.split(".")
    try:
        if "*" in core:
            if core.count("*") > 1 or not core.endswith("*") or len(parts) > 4:
                return None
            level = _STAR_LEVEL[len(parts) - 1]
            if not dash and level == "Major" and core != "*":
                return None                        # `1*` is the plain version 10
            if dash:
                behavior = "AbsoluteLatest" if core == "*" and not prefix else "Prerelease" + level
            else:
                behavior = level
            numbers = _numbers(core.replace("*", "0"), raw)
        elif dash:
            behavior, numbers = "Prerelease", _numbers(core, raw)
        else:
            return None
        labels: tuple[str, ...] = ()
        if dash:                                   # `beta.*` starts at `beta.0`, `*` at `0`
            labels = _labels(prefix + "0" if prefix == "" or prefix.endswith(".") else prefix, raw)
    except InvalidVersion:
        return None
    return Float(behavior, Version(numbers, labels), prefix)


def _bound(text: str, raw: str, *, bracketed: bool) -> tuple[Version, Float | None]:
    floating = _parse_float(text, raw)
    if floating is not None:
        return floating.min, floating
    star_only = text.endswith("*") and text.count("*") == 1 and "." not in text and "-" not in text
    if star_only and (not bracketed or not text[:-1].strip(_TRIM)):
        return parse(text.replace("*", "0")), None  # a bare `1*` outside brackets reads as 10, `[ *,)` as 0
    return parse(text), None


@dataclass(frozen=True, slots=True)
class NuGetConstraint:
    _raw: str
    min: str | None
    min_inclusive: bool
    max: str | None
    max_inclusive: bool
    floating: str | None                           # float behavior of the lower bound, None for a fixed range
    _min: Version | None
    _max: Version | None
    _float: Float | None

    def raw(self) -> str:
        return self._raw

    @property
    def _prerelease_bounds(self) -> bool:
        return any(bound is not None and bound.is_prerelease for bound in (self._min, self._max))

    def _satisfies(self, version: Version) -> bool:
        if self._min is not None:
            order = self._min.compare(version)
            if order > 0 or (order == 0 and not self.min_inclusive):
                return False
        if self._max is not None:
            order = version.compare(self._max)
            if order > 0 or (order == 0 and not self.max_inclusive):
                return False
        return True

    def contains(self, version: str) -> bool:
        """`VersionRange.Satisfies`: floating is ignored and prereleases are not excluded."""
        try:
            return self._satisfies(parse(version))
        except InvalidVersion:
            return False

    def best_match(self, versions: list[str]) -> str | None:
        """`VersionRange.FindBestMatch`: the lowest satisfying version; for a floating range, the highest of those
        matching the float, and the lowest when none does.

        Prereleases are skipped unless the range names one as a bound. Among equal versions (`1.0` and `1.0.0.0`)
        the first in the list wins. Unparsable entries are skipped.
        """
        best: tuple[str, Version] | None = None
        for raw in versions:
            try:
                version = parse(raw)
            except InvalidVersion:
                continue
            if not self._satisfies(version) or (version.is_prerelease and not self._prerelease_bounds):
                continue
            if best is None or self._is_better(best[1], version):
                best = (raw, version)
        return best[0] if best else None

    def _is_better(self, current: Version, considering: Version) -> bool:
        if self._float is not None:
            current_floats, considering_floats = self._float.satisfies(current), self._float.satisfies(considering)
            if current_floats != considering_floats:
                return considering_floats
            if current_floats:
                return considering.compare(current) > 0
        return considering.compare(current) < 0


@lru_cache(maxsize=16384)
def parse_range(raw: str) -> NuGetConstraint:
    """`VersionRange.TryParse` with floating allowed; raises InvalidVersion where it returns false."""
    text = raw.strip(_TRIM)
    low: Version | None = None
    high: Version | None = None
    floating: Float | None = None
    low_inclusive, high_inclusive = True, False
    if text[:1] in ("(", "[") and text[-1:] in (")", "]"):
        low_inclusive, high_inclusive = text[0] == "[", text[-1] == "]"
        parts = text[1:-1].split(",")
        if len(parts) > 2 or not any(parts):
            raise InvalidVersion(f"invalid NuGet version range {raw!r}")
        low_text, high_text = parts[0], parts[-1]
        if low_text.strip(_TRIM):
            low, floating = _bound(low_text, raw, bracketed=True)
        if high_text.strip(_TRIM):
            high = parse(high_text)
        if len(parts) == 1 and not (low_inclusive and high_inclusive):
            raise InvalidVersion(f"invalid NuGet version range {raw!r}: [x] needs both brackets")
        if low is not None and high is not None:
            order = low.compare(high)
            if order > 0 or (order == 0 and low_inclusive != high_inclusive):
                raise InvalidVersion(f"invalid NuGet version range {raw!r}: empty interval")
    elif text:
        low, floating = _bound(text, raw, bracketed=False)
    else:
        raise InvalidVersion("empty NuGet version range")
    return NuGetConstraint(
        raw, low.normalized() if low else None, low_inclusive and low is not None,
        high.normalized() if high else None, high_inclusive and high is not None,
        floating.behavior if floating else None, low, high, floating)


class NuGetVersionScheme:
    def validate(self, raw: str) -> None:
        parse(raw)

    def sort_key(self, raw: str) -> bytes:
        try:
            return _key(parse(raw))
        except InvalidVersion:
            return fallback_sort_key(raw)

    def is_prerelease(self, raw: str) -> bool:
        try:
            return parse(raw).is_prerelease
        except InvalidVersion:
            return False

    def bump(self, previous: str | None, current: str) -> Bump | None:
        if previous is None:
            return None
        try:
            prev, cur = parse(previous), parse(current)
        except InvalidVersion:
            return "other"
        if cur.is_prerelease:
            return "pre"
        if cur.compare(prev) <= 0:
            return "other"
        if cur.numbers[0] != prev.numbers[0]:
            return "major"
        if cur.numbers[1] != prev.numbers[1]:
            return "minor"
        return "patch"                             # a change in the patch or only in the revision

    def constraint(self, raw: str) -> NuGetConstraint:
        return parse_range(raw)
