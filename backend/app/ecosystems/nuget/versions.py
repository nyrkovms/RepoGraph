"""NuGet versions and version ranges as NuGet.Versioning reads them (SPEC-MULTI-ECOSYSTEM.md §5.5, §9.6).

`NuGetVersion.TryParse` takes one to four numbers (`1`, `1.0`, `1.0.0`, `1.0.0.1`, each up to 2**31-1, leading zeros and
whitespace around a number allowed), an optional `-prerelease` of dot-separated labels and an optional `+metadata`;
the whole string is trimmed first. A numeric label may not have a leading zero. Order is `VersionComparer.Default`:
the four numbers, then SemVer 2 prerelease precedence with labels compared case-insensitively; metadata is ignored.
The normalized form (`ToNormalizedString`) is what the registration publishes: three numbers, the revision only when
it is not 0, the label spelling kept.

A `VersionRange` is `1.0` (= `>= 1.0`), an interval `[1.0,2.0)` / `(,1.0]` / `[1.0]`, optionally with a floating lower
bound (`1.*`, `1.0.*`, `*`, `1.0.0-*`, `1.0.0-beta*`). `Satisfies` ignores floating and compares the interval only,
prereleases included; `FindBestMatch` picks the lowest satisfying version, or for a floating range the highest one that
also matches the float. All of it is checked against vectors generated by NuGet.Versioning itself
(scripts/generate_nuget_version_vectors.sh).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from functools import lru_cache

from app.ecosystems.base import Bump, InvalidVersion
from app.ecosystems.versions_common import encode_number, fallback_sort_key

MAX_NUMBER = 2**31 - 1
Identifier = int | str

# char.IsWhiteSpace: what the outer Trim() removes. Python's str.strip also removes U+001C..U+001F, which .NET keeps.
_TRIM = "\t\n\v\f\r \x85\xa0" \
        "\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a\u2028\u2029\u202f\u205f\u3000"
_NUMBER = re.compile(r"[0-9]+")
_SIGNED = re.compile(r"-?[0-9]+")
_LABEL = re.compile(r"[0-9A-Za-z-]+")


@dataclass(frozen=True, slots=True)
class Version:
    numbers: tuple[int, int, int, int]
    labels: tuple[str, ...] = ()                   # release labels as written

    @property
    def is_prerelease(self) -> bool:
        return bool(self.labels)

    def normalized(self) -> str:
        major, minor, patch, revision = self.numbers
        text = f"{major}.{minor}.{patch}" + (f".{revision}" if revision else "")
        return text + ("-" + ".".join(self.labels) if self.labels else "")

    def identifiers(self) -> tuple[Identifier, ...]:
        """Labels as comparable identifiers: numeric ones by value, the rest lowercased (OrdinalIgnoreCase).

        NuGet reads a label as a number with `int.TryParse`: `-1` is the number -1 and a run of digits too big for an
        int is text.
        """
        idents: list[Identifier] = []
        for label in self.labels:
            number = _label_number(label)
            idents.append(label.lower() if number is None else number)
        return tuple(idents)

    def compare(self, other: Version) -> int:
        if self.numbers != other.numbers:
            return -1 if self.numbers < other.numbers else 1
        return _compare_labels(self.identifiers(), other.identifiers())


def _label_number(label: str) -> int | None:
    if _SIGNED.fullmatch(label) is None:
        return None
    value = int(label)
    return value if -MAX_NUMBER - 1 <= value <= MAX_NUMBER else None


def _compare_labels(a: tuple[Identifier, ...], b: tuple[Identifier, ...]) -> int:
    if not a or not b:
        return (len(b) > 0) - (len(a) > 0)         # a release is greater than any prerelease of it
    for x, y in zip(a, b):
        if x == y:
            continue
        if isinstance(x, int) and isinstance(y, int):
            return -1 if x < y else 1
        if isinstance(x, int):
            return -1                              # numbers sort below text
        if isinstance(y, int):
            return 1
        return -1 if x < y else 1
    return (len(a) > len(b)) - (len(a) < len(b))


def _numbers(core: str, raw: str) -> tuple[int, int, int, int]:
    parts = core.split(".")
    if len(parts) > 4:
        raise InvalidVersion(f"{raw!r}: more than four numbers")
    numbers = []
    for part in parts:
        text = part.strip(_TRIM)
        if _NUMBER.fullmatch(text) is None or int(text) > MAX_NUMBER:
            raise InvalidVersion(f"{raw!r}: {part!r} is not a version number")
        numbers.append(int(text))
    numbers += [0] * (4 - len(numbers))
    return (numbers[0], numbers[1], numbers[2], numbers[3])


def _labels(text: str, raw: str) -> tuple[str, ...]:
    labels = text.split(".")
    for label in labels:
        if _LABEL.fullmatch(label) is None or (label.isdecimal() and len(label) > 1 and label[0] == "0"):
            raise InvalidVersion(f"{raw!r}: invalid release label {label!r}")
    return tuple(labels)


@lru_cache(maxsize=65536)
def parse(raw: str) -> Version:
    text = raw.strip(_TRIM)
    cut = min((i for i in (text.find("-"), text.find("+")) if i >= 0), default=len(text))
    core, rest = text[:cut], text[cut:]
    numbers = _numbers(core, raw)
    labels: tuple[str, ...] = ()
    if rest.startswith("-"):
        label_text, plus, metadata = rest[1:].partition("+")
        labels = _labels(label_text, raw)
    else:
        plus, metadata = ("+", rest[1:]) if rest else ("", "")
    if plus and not all(_LABEL.fullmatch(part) for part in metadata.split(".")):
        raise InvalidVersion(f"{raw!r}: invalid build metadata")
    return Version(numbers, labels)


def normalize(raw: str) -> str:
    """`NuGetVersion.ToNormalizedString()`: `1.0` -> `1.0.0`, `1.0.0.0` -> `1.0.0`, `1.0.0.1` stays, metadata dropped."""
    return parse(raw).normalized()


def _key(version: Version) -> bytes:
    """Same layout as `versions_common.semver_key`, with the revision as a fourth number and labels lowercased.

    Label tags: 0x01 negative number (`-1` is a number to NuGet), 0x02 other number, 0x03 text.
    """
    out = b"".join(encode_number(str(n)) for n in version.numbers)
    if not version.labels:
        return out + b"\x02"                       # a release sorts after every prerelease of it
    out += b"\x01"
    for ident in version.identifiers():
        if isinstance(ident, str):
            out += b"\x03" + ident.encode() + b"\x00"
        elif ident < 0:
            out += b"\x01" + encode_number(str(10**10 + ident))   # ten digits for every int: more negative sorts first
        else:
            out += b"\x02" + encode_number(str(ident))
    return out + b"\x00"                           # fewer labels sort first


