"""crates.io versions and requirements: SemVer 2.0 as the `semver` crate (the one Cargo uses) reads them
(SPEC-MULTI-ECOSYSTEM.md §5.5).

Versions are strict `MAJOR.MINOR.PATCH[-pre][+build]` with u64 numbers. A requirement is comma-separated comparators;
a bare version means `^`. Comparators are evaluated the way the crate does it (`eval.rs`), part by part, rather than
desugared into bounds: `>1.2` compares major and minor only, which differs from `>=1.3.0` once prereleases are
involved. A prerelease version matches only if a comparator names a prerelease on its major.minor.patch.
Compatibility is checked against vectors generated by the crate itself (scripts/generate_cargo_semver_vectors.sh).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from functools import lru_cache

from app.ecosystems.base import Bump, Constraint, InvalidVersion
from app.ecosystems.versions_common import fallback_sort_key, semver_key

MAX_U64 = 2**64 - 1
_NUM = r"0|[1-9][0-9]*"
_IDENT = r"[0-9A-Za-z-]+"
_PRE = rf"(?:{_IDENT})(?:\.{_IDENT})*"
_VERSION = re.compile(rf"^({_NUM})\.({_NUM})\.({_NUM})(?:-({_PRE}))?(?:\+({_PRE}))?$")
Identifier = int | str


def _compare_prerelease(a: tuple[Identifier, ...], b: tuple[Identifier, ...]) -> int:
    if not a or not b:
        return (len(b) > 0) - (len(a) > 0)   # no prerelease is greater than any prerelease
    for x, y in zip(a, b):
        if x == y:
            continue
        if isinstance(x, int) and isinstance(y, int):
            return -1 if x < y else 1
        if isinstance(x, int):
            return -1                      # numeric identifiers sort below alphanumeric ones
        if isinstance(y, int):
            return 1
        return -1 if x < y else 1
    return (len(a) > len(b)) - (len(a) < len(b))


@dataclass(frozen=True, slots=True)
class Version:
    major: int
    minor: int
    patch: int
    prerelease: tuple[Identifier, ...] = ()

    @property
    def triple(self) -> tuple[int, int, int]:
        return (self.major, self.minor, self.patch)

    def compare(self, other: Version) -> int:
        """Precedence: build metadata is ignored (crates.io refuses versions that differ only in it)."""
        if self.triple != other.triple:
            return -1 if self.triple < other.triple else 1
        return _compare_prerelease(self.prerelease, other.prerelease)


def _number(text: str, raw: str) -> int:
    value = int(text)
    if value > MAX_U64:
        raise InvalidVersion(f"{raw}: {text} does not fit in u64")
    return value


def _prerelease(text: str, raw: str) -> tuple[Identifier, ...]:
    parts = text.split(".")
    if any(part.isdigit() and len(part) > 1 and part.startswith("0") for part in parts):
        raise InvalidVersion(f"{raw}: leading zero in a prerelease identifier")
    # Numeric identifiers compare by value with no upper limit, unlike the version numbers.
    return tuple(int(part) if part.isdigit() else part for part in parts)


@lru_cache(maxsize=65536)
def parse(raw: str) -> Version:
    match = _VERSION.fullmatch(raw)
    if match is None:
        raise InvalidVersion(raw)
    prerelease = _prerelease(match[4], raw) if match[4] else ()
    return Version(_number(match[1], raw), _number(match[2], raw), _number(match[3], raw), prerelease)


def compatibility(raw: str) -> str:
    """Cargo's semver-compatibility class: `1` for 1.x.y, `0.3` for 0.3.x, `0.0.3`; versions of one class unify."""
    version = parse(raw)
    if version.major:
        return str(version.major)
    if version.minor:
        return f"0.{version.minor}"
    return f"0.0.{version.patch}"


# --- requirements ----------------------------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Comparator:
    operator: str                                  # "=", ">", ">=", "<", "<=", "~", "^" or "*" (`1.*`)
    major: int
    minor: int | None
    patch: int | None
    prerelease: tuple[Identifier, ...] = ()

    def _exact(self, v: Version) -> bool:
        if v.major != self.major or (self.minor is not None and v.minor != self.minor):
            return False
        if self.patch is not None and v.patch != self.patch:
            return False
        return v.prerelease == self.prerelease

    def _greater(self, v: Version) -> bool:
        if v.major != self.major:
            return v.major > self.major
        if self.minor is None:
            return False
        if v.minor != self.minor:
            return v.minor > self.minor
        if self.patch is None:
            return False
        if v.patch != self.patch:
            return v.patch > self.patch
        return _compare_prerelease(v.prerelease, self.prerelease) > 0

    def _less(self, v: Version) -> bool:
        if v.major != self.major:
            return v.major < self.major
        if self.minor is None:
            return False
        if v.minor != self.minor:
            return v.minor < self.minor
        if self.patch is None:
            return False
        if v.patch != self.patch:
            return v.patch < self.patch
        return _compare_prerelease(v.prerelease, self.prerelease) < 0

    def _tilde(self, v: Version) -> bool:
        if v.major != self.major or (self.minor is not None and v.minor != self.minor):
            return False
        if self.patch is not None and v.patch != self.patch:
            return v.patch > self.patch
        return _compare_prerelease(v.prerelease, self.prerelease) >= 0

    def _caret(self, v: Version) -> bool:
        if v.major != self.major:
            return False
        if self.minor is None:
            return True
        if self.patch is None:
            return v.minor >= self.minor if self.major > 0 else v.minor == self.minor
        if self.major > 0:
            if v.minor != self.minor:
                return v.minor > self.minor
            if v.patch != self.patch:
                return v.patch > self.patch
        elif self.minor > 0:
            if v.minor != self.minor:
                return False
            if v.patch != self.patch:
                return v.patch > self.patch
        elif v.minor != self.minor or v.patch != self.patch:
            return False
        return _compare_prerelease(v.prerelease, self.prerelease) >= 0

    def test(self, v: Version) -> bool:
        match self.operator:
            case "=" | "*":
                return self._exact(v)
            case ">":
                return self._greater(v)
            case ">=":
                return self._exact(v) or self._greater(v)
            case "<":
                return self._less(v)
            case "<=":
                return self._exact(v) or self._less(v)
            case "~":
                return self._tilde(v)
            case _:
                return self._caret(v)

    def names_prerelease_of(self, v: Version) -> bool:
        return bool(self.prerelease) and (self.major, self.minor, self.patch) == v.triple


_OPERATOR = re.compile(r"^(>=|<=|=|>|<|~|\^)?")
_WILDCARDS = "*xX"
_PART = re.compile(rf"^(?:{_NUM}|[*xX])")
MAX_COMPARATORS = 32


def _comparator(text: str, raw: str) -> Comparator:
    operator_match = _OPERATOR.match(text)
    written = operator_match[1] if operator_match and operator_match[1] else ""
    rest = text[len(written):].lstrip(" ")
    operator = written or "^"

    def fail() -> InvalidVersion:
        return InvalidVersion(f"invalid Cargo requirement {raw!r}")

    major_match = re.match(_NUM, rest)
    if major_match is None:
        raise fail()                               # `*` is only allowed as the whole requirement
    major, rest = _number(major_match[0], raw), rest[major_match.end():]
    minor: int | None = None
    patch: int | None = None
    wildcard = False
    for position in ("minor", "patch"):
        if not rest.startswith("."):
            break
        part = _PART.match(rest[1:])
        if part is None:
            raise fail()
        rest = rest[1 + part.end():]
        if part[0] in _WILDCARDS:
            wildcard = True
            if not written:
                operator = "*"
        elif wildcard:
            raise fail()                           # `1.*.3`
        elif position == "minor":
            minor = _number(part[0], raw)
        else:
            patch = _number(part[0], raw)
    prerelease: tuple[Identifier, ...] = ()
    if patch is not None and rest.startswith("-"):
        pre = re.match(_PRE, rest[1:])
        if pre is None:
            raise fail()
        prerelease, rest = _prerelease(pre[0], raw), rest[1 + pre.end():]
    if patch is not None and rest.startswith("+"):
        build = re.match(_PRE, rest[1:])
        if build is None:
            raise fail()
        rest = rest[1 + build.end():]
    if rest.strip(" "):
        raise fail()
    return Comparator(operator, major, minor, patch, prerelease)


@lru_cache(maxsize=16384)
def parse_requirement(raw: str) -> tuple[Comparator, ...]:
    text = raw.lstrip(" ")
    if text[:1] and text[0] in _WILDCARDS:
        if text[1:].strip(" "):
            raise InvalidVersion(f"invalid Cargo requirement {raw!r}: `*` must be the only comparator")
        return ()                                  # any version
    parts = text.split(",")
    if len(parts) > MAX_COMPARATORS:
        raise InvalidVersion(f"invalid Cargo requirement {raw!r}: more than {MAX_COMPARATORS} comparators")
    return tuple(_comparator(part.strip(" "), raw) for part in parts)


def matches(comparators: tuple[Comparator, ...], version: Version) -> bool:
    if not all(c.test(version) for c in comparators):
        return False
    return not version.prerelease or any(c.names_prerelease_of(version) for c in comparators)


@dataclass(frozen=True, slots=True)
class CargoConstraint:
    _raw: str
    comparators: tuple[Comparator, ...]

    def contains(self, version: str) -> bool:
        try:
            parsed = parse(version)
        except InvalidVersion:
            return False
        return matches(self.comparators, parsed)

    def raw(self) -> str:
        return self._raw


class CratesVersionScheme:
    def validate(self, raw: str) -> None:
        parse(raw)

    def sort_key(self, raw: str) -> bytes:
        try:
            version = parse(raw)
        except InvalidVersion:
            return fallback_sort_key(raw)
        return semver_key(version.triple, version.prerelease)

    def is_prerelease(self, raw: str) -> bool:
        try:
            return bool(parse(raw).prerelease)
        except InvalidVersion:
            return False

    def bump(self, previous: str | None, current: str) -> Bump | None:
        if previous is None:
            return None
        try:
            prev, cur = parse(previous), parse(current)
        except InvalidVersion:
            return "other"
        if cur.prerelease:
            return "pre"
        if cur.compare(prev) <= 0:
            return "other"
        if cur.major != prev.major:
            return "major"
        if cur.minor != prev.minor:
            return "minor"
        return "patch"

    def constraint(self, raw: str) -> Constraint:
        return CargoConstraint(raw, parse_requirement(raw))
