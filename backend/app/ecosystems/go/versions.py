"""Go module versions: SemVer with a `v` prefix as golang.org/x/mod/semver reads it, plus pseudo-versions and
`+incompatible` (SPEC-MULTI-ECOSYSTEM.md §5.5, §9.5).

A module version always has three numbers, `vMAJOR.MINOR.PATCH[-pre][+build]`; the shorthands `v1` and `v1.2` that
`semver.IsValid` accepts are rejected. Numbers compare as decimal strings, so there is no upper limit (apart from
`MAX_DIGITS`, the most the byte sort key can encode). Order is `semver.Compare`: build metadata is ignored, so
`v2.0.0+incompatible` equals `v2.0.0`, and a pseudo-version is an ordinary prerelease. Go has no ranges: a requirement
`v1.2.3` means "at least v1.2.3" (Minimal Version Selection). Checked against vectors generated by Go itself
(scripts/generate_go_semver_vectors.sh).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import UTC, datetime
from functools import lru_cache

from app.ecosystems.base import Bump, Constraint, InvalidVersion
from app.ecosystems.versions_common import fallback_sort_key, semver_key

MAX_DIGITS = 255
_NUM = r"0|[1-9][0-9]*"
_IDENT = r"[0-9A-Za-z-]+"
_PRE = rf"(?:{_IDENT})(?:\.{_IDENT})*"
_VERSION = re.compile(rf"v({_NUM})\.({_NUM})\.({_NUM})(?:-({_PRE}))?(?:\+({_PRE}))?")
# module.IsPseudoVersion's expression, with ASCII classes spelled out. The revision is any alphanumeric run.
_PSEUDO = re.compile(
    r"v[0-9]+\.(?:0\.0-|[0-9]+\.[0-9]+-(?:[^+]*\.)?0\.)[0-9]{14}-[A-Za-z0-9]+(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?")
Identifier = int | str


@dataclass(frozen=True, slots=True)
class Version:
    major: int
    minor: int
    patch: int
    prerelease: tuple[Identifier, ...] = ()
    build: str = ""

    @property
    def triple(self) -> tuple[int, int, int]:
        return (self.major, self.minor, self.patch)


def _number(text: str, raw: str) -> int:
    if len(text) > MAX_DIGITS:
        raise InvalidVersion(f"{raw}: a number of {len(text)} digits is more than the sort key can hold")
    return int(text)


def _prerelease(text: str, raw: str) -> tuple[Identifier, ...]:
    parts = text.split(".")
    if any(part.isdigit() and len(part) > 1 and part.startswith("0") for part in parts):
        raise InvalidVersion(f"{raw}: leading zero in a prerelease identifier")
    return tuple(_number(part, raw) if part.isdigit() else part for part in parts)


@lru_cache(maxsize=65536)
def parse(raw: str) -> Version:
    match = _VERSION.fullmatch(raw)
    if match is None:
        raise InvalidVersion(raw)
    prerelease = _prerelease(match[4], raw) if match[4] else ()
    return Version(
        _number(match[1], raw), _number(match[2], raw), _number(match[3], raw), prerelease, match[5] or "")


def _key(raw: str) -> bytes:
    version = parse(raw)
    return semver_key(version.triple, version.prerelease)


def compare(a: str, b: str) -> int:
    """`semver.Compare` for two valid versions: -1, 0 or 1."""
    key_a, key_b = _key(a), _key(b)
    return (key_a > key_b) - (key_a < key_b)


# --- pseudo-versions and helpers -------------------------------------------------------------------------------


def is_pseudo(raw: str) -> bool:
    """`module.IsPseudoVersion`: vX.0.0-yyyymmddhhmmss-rev, vX.Y.Z-pre.0.yyyymmddhhmmss-rev or vX.Y.(Z+1)-0.yyyy…-rev."""
    try:
        parse(raw)
    except InvalidVersion:
        return False
    return _PSEUDO.fullmatch(raw) is not None


def _pseudo_parts(raw: str) -> tuple[str, str] | None:
    """(timestamp, revision) split the way `module.parsePseudoVersion` does, or None if raw is no pseudo-version."""
    if not is_pseudo(raw):
        return None
    build = parse(raw).build
    head, _, revision = (raw[:-len(build) - 1] if build else raw).rpartition("-")
    dash, dot = head.rfind("-"), head.rfind(".")
    return (head[dot + 1:] if dot > dash else head[dash + 1:]), revision


def pseudo_time(raw: str) -> datetime | None:
    """UTC commit time of a pseudo-version; None for any other version and for a timestamp that is no real date."""
    parts = _pseudo_parts(raw)
    if parts is None:
        return None
    stamp = parts[0]
    try:
        return datetime(int(stamp[:4]), int(stamp[4:6]), int(stamp[6:8]),
                        int(stamp[8:10]), int(stamp[10:12]), int(stamp[12:14]), tzinfo=UTC)
    except ValueError:
        return None


def pseudo_revision(raw: str) -> str | None:
    """Revision identifier of a pseudo-version (usually a 12-hex commit prefix, but Go accepts any alphanumerics)."""
    parts = _pseudo_parts(raw)
    return None if parts is None else parts[1]


def is_incompatible(raw: str) -> bool:
    """True for `+incompatible`: a v2+ version of a module that has no go.mod and is treated as v0/v1-style."""
    try:
        return parse(raw).build == "incompatible"
    except InvalidVersion:
        return False


def major(raw: str) -> int:
    return parse(raw).major


# --- requirements ----------------------------------------------------------------------------------------------


ANY = ("", "*")


def is_valid(version: str) -> bool:
    try:
        parse(version)
    except InvalidVersion:
        return False
    return True


@dataclass(frozen=True, slots=True)
class MinimumVersion:
    """`require path v1.2.3`: at least that version. Whether the major version path matches is the caller's concern."""

    _raw: str

    def contains(self, version: str) -> bool:
        if self._raw in ANY:
            return is_valid(version)
        try:
            return compare(version, self._raw) >= 0
        except InvalidVersion:
            return False

    def raw(self) -> str:
        return self._raw


class GoVersionScheme:
    def is_valid(self, raw: str) -> bool:
        return is_valid(raw)

    def validate(self, raw: str) -> None:
        parse(raw)

    def sort_key(self, raw: str) -> bytes:
        try:
            return _key(raw)
        except InvalidVersion:
            return fallback_sort_key(raw)

    def is_prerelease(self, raw: str) -> bool:
        try:
            return bool(parse(raw).prerelease)         # every pseudo-version is formally a prerelease
        except InvalidVersion:
            return False

    def bump(self, previous: str | None, current: str) -> Bump | None:
        if previous is None:
            return None
        try:
            prev, cur = parse(previous), parse(current)
        except InvalidVersion:
            return "other"
        if self.is_prerelease(current):
            return "pre"
        if compare(current, previous) <= 0:
            return "other"
        if cur.major != prev.major:
            return "major"
        if cur.minor != prev.minor:
            return "minor"
        return "patch"

    def constraint(self, raw: str) -> Constraint:
        """A version (the minimum MVS starts from), or `*`/empty for a root asked without one (`go get path@latest`)."""
        if raw.strip() not in ANY:
            parse(raw)
        return MinimumVersion(raw.strip())
